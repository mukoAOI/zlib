const std = @import("std");
const Io = std.Io;

const zconf_unistd_template = "#ifdef HAVE_UNISTD_H    /* may be set to #if 1 by configure/cmake/etc */\n#  define Z_HAVE_UNISTD_H\n#endif";
const zlib_zconf_unistd_needle = "#ifdef HAVE_UNISTD_H    /* may be set to #if 1 by ./configure */\n#  define Z_HAVE_UNISTD_H\n#endif";
const zlib_zconf_unistd_on = "#if 1               /* set to #if 1 by zlib_build */\n#  define Z_HAVE_UNISTD_H\n#endif";
const zlib_zconf_unistd_off = "#if 0               /* set to #if 0 by zlib_build */\n#  define Z_HAVE_UNISTD_H\n#endif";
const zconf_zprefix_needle = "#ifdef Z_PREFIX     /* may be set to #if 1 by ./configure */";
const zconf_zprefix_replacement = "#if 1               /* was set to #if 1 by ./configure */";

pub const Replacement = struct {
    needle: []const u8,
    replacement: []const u8,
};

pub fn readSourceFile(io: Io, allocator: std.mem.Allocator, source_root: []const u8, name: []const u8) ![]const u8 {
    const path = try std.fs.path.join(allocator, &.{ source_root, name });
    defer allocator.free(path);
    return Io.Dir.cwd().readFileAlloc(io, path, allocator, .limited(std.math.maxInt(usize)));
}

pub fn applyReplacements(allocator: std.mem.Allocator, input: []const u8, replacements: []const Replacement) ![]const u8 {
    var out: []const u8 = try allocator.dupe(u8, input);
    for (replacements) |r| {
        const next = try std.mem.replaceOwned(u8, allocator, out, r.needle, r.replacement);
        if (out.ptr != input.ptr) allocator.free(out);
        out = next;
    }
    return out;
}

pub fn generateZlibNgZconf(io: Io, allocator: std.mem.Allocator, source_root: []const u8, have_unistd: bool) ![]const u8 {
    const input = try readSourceFile(io, allocator, source_root, "zconf.h.in");
    const unistd_replacement = if (have_unistd)
        "#if 1    /* generated by zlib_build */\n#  define Z_HAVE_UNISTD_H\n#endif"
    else
        "#if 0    /* generated by zlib_build */\n#  define Z_HAVE_UNISTD_H\n#endif";
    return applyReplacements(allocator, input, &.{
        .{ .needle = zconf_unistd_template, .replacement = unistd_replacement },
    });
}

pub fn generateZlibNgFromTemplate(
    io: Io,
    allocator: std.mem.Allocator,
    source_root: []const u8,
    template_name: []const u8,
    symbol_prefix: []const u8,
) ![]const u8 {
    const input = try readSourceFile(io, allocator, source_root, template_name);
    return applyReplacements(allocator, input, &.{
        .{ .needle = "@ZLIB_SYMBOL_PREFIX@", .replacement = symbol_prefix },
    });
}

pub fn generateZlibNgNameMangling(io: Io, allocator: std.mem.Allocator, source_root: []const u8, symbol_prefix: []const u8) ![]const u8 {
    if (symbol_prefix.len == 0) {
        return readSourceFile(io, allocator, source_root, "zlib_name_mangling.h.empty");
    }
    return generateZlibNgFromTemplate(io, allocator, source_root, "zlib_name_mangling.h.in", symbol_prefix);
}

pub fn generateZlibZconf(io: Io, allocator: std.mem.Allocator, source_root: []const u8, have_unistd: bool, zprefix: bool) ![]const u8 {
    const input = try readSourceFile(io, allocator, source_root, "zconf.h");
    var replacements: [2]Replacement = undefined;
    var len: usize = 0;
    replacements[len] = .{
        .needle = zlib_zconf_unistd_needle,
        .replacement = if (have_unistd) zlib_zconf_unistd_on else zlib_zconf_unistd_off,
    };
    len += 1;
    if (zprefix) {
        replacements[len] = .{ .needle = zconf_zprefix_needle, .replacement = zconf_zprefix_replacement };
        len += 1;
    }
    return applyReplacements(allocator, input, replacements[0..len]);
}

pub fn generateZlibH(io: Io, allocator: std.mem.Allocator, source_root: []const u8) ![]const u8 {
    return readSourceFile(io, allocator, source_root, "zlib.h");
}
